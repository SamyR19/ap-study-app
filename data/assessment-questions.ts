// Helper to get questions for a specific curriculum and units
export function getAssessmentQuestionsForUnits(
  curriculum: '4-unit' | '9-unit',
  maxUnit: number
): AssessmentQuestion[] {
  const questions = curriculum === '4-unit'
    ? assessmentQuestions4Unit
    : assessmentQuestions9Unit;

  return questions.filter(q => q.unit_number <= maxUnit);
}

// Get question count info
export function getQuestionCountInfo(
  curriculum: '4-unit' | '9-unit',
  maxUnit: number
): { total: number; perUnit: number } {
  const questions = getAssessmentQuestionsForUnits(curriculum, maxUnit);
  return {
    total: questions.length,
    perUnit: 5,
  };
}
