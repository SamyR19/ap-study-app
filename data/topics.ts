// Helper functions
export function getTopicsByUnit(unitNumber: number): Topic[] {
  return AP_CSA_TOPICS.filter((t) => t.unitNumber === unitNumber);
}

export function getTopicById(id: string): Topic | undefined {
  return AP_CSA_TOPICS.find((t) => t.id === id);
}

export function getTopicsByDifficulty(difficulty: Difficulty): Topic[] {
  return AP_CSA_TOPICS.filter((t) => t.estimatedDifficulty === difficulty);
}

export function getUnitSummary(): { unitNumber: number; unitName: string; topicCount: number }[] {
  const units = new Map<number, { unitName: string; topicCount: number }>();

  AP_CSA_TOPICS.forEach((topic) => {
    if (!units.has(topic.unitNumber)) {
      units.set(topic.unitNumber, { unitName: topic.unitName, topicCount: 0 });
    }
    const unit = units.get(topic.unitNumber)!;
    unit.topicCount++;
  });

  return Array.from(units.entries()).map(([unitNumber, data]) => ({
    unitNumber,
    ...data,
  }));
}

