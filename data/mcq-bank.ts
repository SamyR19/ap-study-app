// Helper functions
export function getQuestionsByTopic(topicId: string): MCQQuestion[] {
  return MCQ_BANK.filter((q) => q.topic === topicId);
}

export function getQuestionsByDifficulty(difficulty: 'easy' | 'medium' | 'hard'): MCQQuestion[] {
  return MCQ_BANK.filter((q) => q.difficulty === difficulty);
}

export function getRandomQuestions(count: number, topicId?: string): MCQQuestion[] {
  let pool = topicId ? getQuestionsByTopic(topicId) : MCQ_BANK;
  const shuffled = [...pool].sort(() => Math.random() - 0.5);
  return shuffled.slice(0, count);
}

export function getQuestionById(id: string): MCQQuestion | undefined {
  return MCQ_BANK.find((q) => q.id === id);
}
